export type Dict = (typeof DICT)["en"];

const LangContext = createContext<{ lang: Lang; t: Dict; setLang: (l: Lang) => void }>({
  lang: "en",
  t: DICT.en as Dict,
  setLang: () => {},
});

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    const fromUrl = new URLSearchParams(window.location.search).get("lang");
    if (fromUrl === "ar" || fromUrl === "en") return setLangState(fromUrl);
    try {
      const saved = localStorage.getItem("tg-lang");
      if (saved === "ar" || saved === "en") setLangState(saved);
    } catch {}
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
    // The layout stays in the same place in both languages; only the words change (Arabic text flows right to left inside its box).
    document.documentElement.dir = "ltr";
  }, [lang]);
  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("tg-lang", l);
    } catch {}
  };
  return <LangContext.Provider value={{ lang, t: DICT[lang] as Dict, setLang }}>{children}</LangContext.Provider>;
}

export const useLang = () => useContext(LangContext);
